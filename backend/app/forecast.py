"""Narrow checks for blanket price-forecast bans, not forecast validity itself."""
import re


PRICE_FORECAST_POLICY = """Ограничивай вывод недостаточностью конкретных оснований, а не запрещай прогнозировать цены вообще.
Прогноз цен допустим при наличии применимых данных и явных допущений: проверь товар, рынок, дату, горизонт прогноза, механизм и ссылки на основания. Не выдавай сценарий за установленный факт; одного упоминания темы в источнике недостаточно.
Новость о достаточности выпуска дизеля и возобновлении экспорта сама по себе не подтверждает направление или величину изменения цен. Допустимо: «Не выводить прогноз цен на дизель только из этой новости; для прогноза нужны дополнительные применимые данные и явные допущения».
Неверно: «Цены на топливо в план не прогнозировать». Это общий запрет, которого отсутствие прогноза в одной новости не обосновывает. Нельзя расширять «этой новости недостаточно» до «прогнозирование недопустимо».
При самопроверке такой общий запрет в рекомендациях или ограничениях — ошибка области вывода: укажи конкретный пункт в checks с category=scope и исправление его условия, а не только editorial_notes. При этом не отклоняй прогноз лишь за слово «прогноз»: проверь его собственные основания. Правильное ограничение одной новостью не оправдывает неподтверждённый прогноз в другом предложении."""

_BAN = re.compile(
    r'\b(?:не\s+(?:(?:нужно|следует|стоит|надо)\s+)?|нельзя\s+)'
    r'(?:прогнозир\w*|(?:строить|делать|составлять)\s+прогноз\w*)\b')
_PRICE = re.compile(r'\bцен(?:а|ы|у|е|ой|ам|ами|ах)?\b|\bценов\w*')
_PRICE_OBJECT = re.compile(r'^\s+(?:(?:изменени\w*|направлени\w*|динамик\w*|рост|снижени\w*|будущ\w*)\s+){0,2}(?:' + _PRICE.pattern + ')')
_SCOPED_SOURCE = re.compile(
    r'\b(?:из|по|на\s+(?:основе|основании))\s+'
    r'(?:(?:только|лишь|исключительно)\s+)?'
    r'(?:(?:этой|этого|данной|данного|одной|одного|текущей|единственной)\s+){1,2}'
    r'(?:новост\w*|стать\w*|публикац\w*|сообщен\w*)\b')
_MISSING_INPUTS = re.compile(
    r'\b(?:без|до\s+получения)\s+'
    r'(?:(?:дополнительн\w*|актуальн\w*|подтвержденн\w*|применим\w*|достаточн\w*|нов\w*)\s+){0,2}'
    r'(?:данных|оснований|котировок|расчетов)\b')
_ABSOLUTE = re.compile(r'\bвообще\b|\bникогда\b|\bни\s+при\s+каких\b')
_REJECTS_BAN = re.compile(r'\b(?:не|нельзя)\s+(?:писать|пишите|рекомендовать|советовать|утверждать)\b')


def price_forecast_issues(text):
    """Scope exceptions to the ban's clause; disclaimers elsewhere cannot waive it."""
    for sentence in re.split(r'[;.!?\n]', text):
        clause = ' '.join(sentence.lower().replace('ё', 'е').split())
        ban = _BAN.search(clause)
        if not ban or _REJECTS_BAN.search(clause[:ban.start()]):
            continue
        before = re.split(r'[:,]', clause[:ban.start()])[-1]
        if not _PRICE.search(before) and not _PRICE_OBJECT.search(clause[ban.end():]):
            continue
        if not _ABSOLUTE.search(clause) and (_SCOPED_SOURCE.search(clause) or _MISSING_INPUTS.search(clause)):
            continue
        return ['Необоснованный общий запрет прогнозировать цены. Ограничьте вывод конкретной новостью: '
                'не делать прогноз только из неё; прогноз по дополнительным применимым данным и явным допущениям допустим. '
                'Его фактические основания всё равно требуют проверки.']
    return []


def forecast_findings(items):
    return {item_id: issues for item_id, item in items.items()
            if item_id.split('.')[0] in ('impact', 'risks', 'opportunities', 'actions', 'answer', 'limitations')
            and (issues := price_forecast_issues(item['text']))}
